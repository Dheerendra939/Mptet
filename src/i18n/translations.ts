/**
 * Detect user's device language accurately from navigator
 */
export function detectDeviceLanguage(): SupportedLanguage {
  try {
    if (typeof window === "undefined" || !navigator) return "en";
    
    // Check localStorage override first if user manually tested another language
    const saved = localStorage.getItem("preferred_app_language") as SupportedLanguage | null;
    if (saved && translations[saved]) {
      return saved;
    }

    const browserLangs = navigator.languages || [navigator.language || "en"];
    for (const rawLang of browserLangs) {
      if (!rawLang) continue;
      const code = rawLang.toLowerCase().split("-")[0] as SupportedLanguage;
      if (translations[code]) {
        return code;
      }
    }
  } catch (e) {
    console.warn("Language detection error:", e);
  }
  return "en";
}
